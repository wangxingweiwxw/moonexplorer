import assert from 'node:assert/strict';
import {mkdir,mkdtemp,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {checkDeployConfig} from './check-deploy-config.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
await mkdir(path.join(root,'_tmp'),{recursive:true});
const fixture=await mkdtemp(path.join(root,'_tmp/deploy-config-test-'));
await assert.rejects(checkDeployConfig(fixture),/缺少或无法读取/);
const file=path.join(fixture,'wrangler.jsonc');
await writeFile(file,JSON.stringify({name:'moonexplorer',assets:{directory:'.'}}));
await assert.rejects(checkDeployConfig(fixture),/Wrangler 配置错误/);
const valid=JSON.parse(await readFile(path.join(root,'wrangler.jsonc'),'utf8'));
await writeFile(file,JSON.stringify(valid));
await assert.rejects(checkDeployConfig(fixture),/源码包上传不完整/);
await mkdir(path.join(fixture,'server'));
for(const name of ['worker.mjs','schema.sql'])await writeFile(path.join(fixture,'server',name),'fixture');
await checkDeployConfig(fixture);
const wrong=structuredClone(valid);wrong.d1_databases[0].database_id='REPLACE_WITH_D1_DATABASE_ID';
await writeFile(file,JSON.stringify(wrong));await assert.rejects(checkDeployConfig(fixture),/D1 UUID/);
await checkDeployConfig(root);
console.log('PASS: missing config, auto-generated assets-only config, missing backend and placeholder D1 are rejected; real deployment config passes.');
